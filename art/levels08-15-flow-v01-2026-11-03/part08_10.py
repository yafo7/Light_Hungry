def hanging_mirror(b,x,y,src,dst,name):
    start=len(b.items)
    b.mirror(x,y,src,dst,fixed=True)
    del b.items[start]  # Replace the floor-mounted stem with an overhead mounting.
    b.line([(x,y-31),(x,y-70)],C['muted'],2)
    b.label(x+45,y-45,name,18,C['muted'])

